class RoleTemplate {
    constructor({
        role,
        description,
        skillLine1,
        skillLine2,
        skillLine3,
        sets,
        partialSets
    }) {
        this.role = role;
        this.description = description;
        this.skillLine1 = skillLine1;
        this.skillLine2 = skillLine2;
        this.skillLine3 = skillLine3;
        this.sets = sets;
        this.partialSets = partialSets;
    }


}